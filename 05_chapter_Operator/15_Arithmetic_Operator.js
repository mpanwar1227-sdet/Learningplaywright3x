// +,-,*,/,


// Assignment Operator in JS

let a = 10;
let b = 3;


// arithmetic Operators

let sum = a + b; // addition
let sub = a - b;
let mul = a * b;
let div = a / b;

console.log("Sum:", sum);
console.log("Sub:", sub);
console.log("Mul:", mul);
console.log("Div:", div); 

// Modulus -> % -> It will give you reminder 
console.log("Modulus:", a % b); // 1
console.log("Modulus:",13%7); // 6 

console.log(101%2);
console.log(100%2);

// n % 2 == 1 -> odd number, [ n % 2 == 0, even ]

// Exponential **, power 2^3 -> 8

console.log(2 ** 3);

console.log(a ** b); // 10^3 -> 1000