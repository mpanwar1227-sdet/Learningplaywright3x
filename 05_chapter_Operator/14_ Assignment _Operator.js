// Assignment Operator in JS


let x =  10; 
x = "Mohit Panwar"; // reassigning the value of x to a string
console.log(x);


let x1 = 10;

x1 += 5;      // x1 = x1 + 5;
console.log(x1);

x1 -= 3;      // x1 = x1 - 3;
console.log(x1);

x *= 2;       // x = x * 2;
x /= 4;       // x = x / 4;
x %= 4;       // x = x % 4;